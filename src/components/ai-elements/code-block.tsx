export const CodeBlockContent = ({
  code,
  language,
  showLineNumbers = false,
}: {
  code: string;
  language: BundledLanguage;
  showLineNumbers?: boolean;
}) => {
  // Memoized raw tokens for immediate display
  const rawTokens = useMemo(() => createRawTokens(code), [code]);

  const [highlighted, setHighlighted] = useState<{code:string;language:BundledLanguage;result:TokenizedCode}>();
  useEffect(()=>{
    let cancelled=false;
    highlighter ??= loadHighlighter();
    highlighter.then(engine=>{
      if(cancelled)return;
      const result=engine.codeToTokens(code,{lang:language,theme:"github-dark"});
      setHighlighted({code,language,result:{tokens:result.tokens,fg:result.fg??"inherit",bg:result.bg??"transparent"}});
    }).catch(()=>{highlighter=undefined;});
    return ()=>{cancelled=true};
  },[code,language]);
  const tokenized=highlighted?.code===code && highlighted.language===language ? highlighted.result : rawTokens;

  return (
    <div className="relative overflow-auto">
      <CodeBlockBody showLineNumbers={showLineNumbers} tokenized={tokenized} />
    </div>
  );
};

export const CodeBlock = ({
  code,
  language,
  showLineNumbers = false,
  className,
  children,
  ...props
}: CodeBlockProps) => {


  return (

      <CodeBlockContainer className={className} language={language} {...props}>
        {children}
        <CodeBlockContent
          code={code}
          language={language}
          showLineNumbers={showLineNumbers}
        />
      </CodeBlockContainer>

  );
};
